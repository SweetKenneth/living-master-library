#!/usr/bin/env node
// Copy livingcore into one or more product repos as core/, with a hash manifest.
//   node scripts/sync.mjs ../livingpress ../livingchangelog
// Products then import from "../core/*.ts" and their tests run checkVendoredCore().
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, rmSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const files = readdirSync(join(root, "src")).filter((f) => f.endsWith(".ts")).sort();
const targets = process.argv.slice(2);
if (!targets.length) { console.error("usage: node scripts/sync.mjs <product-repo> [...]"); process.exit(1); }

for (const t of targets) {
  const dir = resolve(t, "core");
  if (!existsSync(resolve(t, "package.json"))) { console.error(`skip ${t}: no package.json there`); process.exitCode = 1; continue; }
  if (existsSync(dir)) for (const f of readdirSync(dir)) if (f.endsWith(".ts") && !files.includes(f)) rmSync(join(dir, f)); // drop files the core no longer has
  mkdirSync(dir, { recursive: true });
  const manifest = { name: "livingcore", version: pkg.version, files: {} };
  for (const f of files) {
    const text = readFileSync(join(root, "src", f), "utf8");
    writeFileSync(join(dir, f), text);
    manifest.files[f] = createHash("sha256").update(text).digest("hex");
  }
  writeFileSync(join(dir, "CORE-MANIFEST.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  writeFileSync(join(dir, "README.md"), `# core/ (vendored livingcore ${pkg.version})\n\nGenerated by livingcore's \`scripts/sync.mjs\`. **Do not edit these files here.** Change livingcore, run its tests, then sync. The product's self-test fails if any file here no longer matches \`CORE-MANIFEST.json\`.\n`);
  console.log(`synced livingcore ${pkg.version} -> ${dir} (${files.length} files)`);
}
